import csv
from esquema import T, COLS, ORDEN
def q(s): return '"' + s.replace('"', '""') + '"'
cnt = {t: sum(1 for _ in open("lanops_csv/%s.csv" % t, encoding="utf-8")) - 1 for t in ORDEN}
L = []; a = L.append
a('Attribute VB_Name = "LANOPS_montaje"')
a("Option Compare Database"); a("Option Explicit"); a("")
a("' LANOPS - montaje del .mdb (generado desde esquema.py; no editar a mano, regenerar)")
a("' Paso1_CrearTablas: 13 tablas con tipos, claves, indices, reglas, descripciones y las 15 relaciones con integridad")
a("' Paso2_ImportarCSV: carga los CSV de la carpeta lanops_csv (junto al .mdb) en orden padres -> hijas")
a("' Paso3_Probar: prueba de integridad (usuario 9999), regla de validacion e indice sin duplicados; deshace todo")
a(""); a('Private Const CARPETA As String = "lanops_csv"'); a("")
a("Private Function Tablas() As Variant"); a("    Tablas = Array(" + ", ".join(q(t) for t in ORDEN) + ")"); a("End Function"); a("")
a("Private Sub X(db As DAO.Database, ByVal sql As String)")
a("    On Error GoTo fallo"); a("    db.Execute sql, dbFailOnError"); a("    Exit Sub")
a("fallo:"); a("    Debug.Print sql"); a('    Err.Raise Err.Number, "LANOPS", Err.Description & vbCrLf & vbCrLf & Left(sql, 300)'); a("End Sub"); a("")
a("Private Sub SetProp(obj As Object, ByVal nombre As String, ByVal tipo As Integer, ByVal valor As Variant)")
a("    On Error Resume Next"); a("    obj.Properties(nombre) = valor")
a("    If Err.Number <> 0 Then"); a("        Err.Clear"); a("        obj.Properties.Append obj.CreateProperty(nombre, tipo, valor)"); a("    End If"); a("    On Error GoTo 0"); a("End Sub"); a("")
a("Private Sub Campo(db As DAO.Database, ByVal t As String, ByVal c As String, ByVal desc As String, ByVal regla As String, ByVal txt As String, ByVal defecto As String)")
a("    Dim fld As DAO.Field"); a("    Set fld = db.TableDefs(t).Fields(c)")
a('    SetProp fld, "Description", dbText, desc')
a('    If regla <> "" Then fld.ValidationRule = regla: fld.ValidationText = txt')
a('    If defecto <> "" Then fld.DefaultValue = defecto')
a("    Select Case fld.Type")
a('        Case dbBoolean: SetProp fld, "DisplayControl", dbInteger, 106: SetProp fld, "Format", dbText, "Yes/No"')
a('        Case dbDate: SetProp fld, "Format", dbText, "Short Date"')
a('        Case dbSingle: SetProp fld, "Format", dbText, "Fixed": SetProp fld, "DecimalPlaces", dbByte, 1')
a("    End Select"); a("End Sub"); a("")
a("Private Function Existe(db As DAO.Database, ByVal t As String) As Boolean")
a("    Dim td As DAO.TableDef"); a("    For Each td In db.TableDefs"); a("        If td.Name = t Then Existe = True: Exit Function"); a("    Next"); a("End Function"); a("")
a("Private Function EsNuestra(ByVal t As String) As Boolean")
a("    Dim x As Variant"); a("    For Each x In Tablas()"); a("        If x = t Then EsNuestra = True: Exit Function"); a("    Next"); a("End Function"); a("")
a("Public Sub Paso0_BorrarTablas()")
a("    Dim db As DAO.Database, i As Integer, hay As Boolean, t As Variant")
a("    Set db = CurrentDb")
a("    For Each t In Tablas()")
a("        If Existe(db, CStr(t)) Then hay = True")
a("    Next")
a('    If Existe(db, "tmp_usuarios") Then db.Execute "DROP TABLE tmp_usuarios"')
a("    If Not hay Then Exit Sub")
a('    If MsgBox("Se borraran las tablas de LANOPS y sus datos. ¿Seguir?", vbYesNo + vbExclamation, "LANOPS") = vbNo Then End')
a("    For i = db.Relations.Count - 1 To 0 Step -1")
a("        If EsNuestra(db.Relations(i).Table) Or EsNuestra(db.Relations(i).ForeignTable) Then db.Relations.Delete db.Relations(i).Name")
a("    Next")
a("    For i = UBound(Tablas()) To 0 Step -1")
a('        If Existe(db, Tablas()(i)) Then db.Execute "DROP TABLE [" & Tablas()(i) & "]"')
a("    Next"); a("    db.TableDefs.Refresh"); a("End Sub"); a("")
a("Public Sub Paso1_CrearTablas()")
a("    Dim db As DAO.Database, s As String"); a("    Paso0_BorrarTablas"); a("    Set db = CurrentDb")
for t, desc, cols, cons, extra in T:
    a("    ' ---- " + t)
    a('    s = "CREATE TABLE [%s] ("' % t)
    parts = []
    for c in cols:
        parts.append("[%s] %s%s" % (c["col"], c["ddl"], " NOT NULL" if c["nn"] and c["ddl"] != "COUNTER" else ""))
    parts += cons
    for k, p in enumerate(parts):
        a('    s = s & %s' % q(p + (", " if k < len(parts) - 1 else ")")))
    a("    X db, s")
    for x in extra: a("    X db, %s" % q(x))
a("    db.TableDefs.Refresh")
for t, desc, cols, cons, extra in T:
    a('    SetProp db.TableDefs(%s), "Description", dbText, %s' % (q(t), q(desc)))
    for c in cols:
        a("    Campo db, %s, %s, %s, %s, %s, %s" % (q(t), q(c["col"]), q(c["desc"]), q(c["regla"] or ""), q(c["txt"] or ""), q(c["defecto"] or "")))
a('    MsgBox "Paso 1 hecho: 13 tablas y " & Relaciones(db) & " relaciones con integridad referencial (esperadas: 15).", vbInformation, "LANOPS"')
a("End Sub"); a("")
a("Private Function Relaciones(db As DAO.Database) As Integer")
a("    Dim r As DAO.Relation")
a("    For Each r In db.Relations"); a("        If EsNuestra(r.Table) And EsNuestra(r.ForeignTable) Then Relaciones = Relaciones + 1"); a("    Next"); a("End Function"); a("")
a("Public Sub Paso2_ImportarCSV()")
a("    Dim db As DAO.Database, ruta As String, src As String, t As Variant, i As Integer, msg As String")
a("    Set db = CurrentDb")
a('    ruta = CurrentProject.Path & "\\" & CARPETA')
a('    If Dir(ruta & "\\schema.ini") = "" Then MsgBox "No encuentro " & ruta & "\\schema.ini. Descomprime lanops_csv junto a " & CurrentProject.Name, vbCritical, "LANOPS": Exit Sub')
a('    src = "[Text;DATABASE=" & ruta & ";HDR=Yes]."')
a("    ' vaciar si ya hay datos (hijas primero)")
a("    For i = UBound(Tablas()) To 0 Step -1")
a('        db.Execute "DELETE FROM [" & Tablas()(i) & "]", dbFailOnError')
a("    Next")
a('    If Existe(db, "tmp_usuarios") Then db.Execute "DROP TABLE tmp_usuarios"')
for t in ORDEN:
    cols = ", ".join("[%s]" % c for c in COLS[t])
    if t == "USUARIOS":
        sin = ", ".join("[%s]" % c for c in COLS[t] if c != "recomendado_por")
        a('    X db, "SELECT * INTO tmp_usuarios FROM " & src & "[USUARIOS#csv]"')
        a('    X db, "INSERT INTO [USUARIOS] (%s) SELECT %s FROM tmp_usuarios ORDER BY [id]"' % (sin, sin))
        a('    X db, "UPDATE [USUARIOS] INNER JOIN tmp_usuarios ON [USUARIOS].[id] = tmp_usuarios.[id] SET [USUARIOS].[recomendado_por] = tmp_usuarios.[recomendado_por] WHERE tmp_usuarios.[recomendado_por] Is Not Null"')
        a('    X db, "DROP TABLE tmp_usuarios"')
    else:
        a('    X db, "INSERT INTO [%s] (%s) SELECT %s FROM " & src & "[%s#csv]"' % (t, cols, cols, t))
a('    msg = "Registros importados (esperados):" & vbCrLf')
for t in ORDEN:
    a('    msg = msg & %s & DCount("*", %s) & "  (%d)" & vbCrLf' % (q(t + ": "), q(t), cnt[t]))
a('    MsgBox msg, vbInformation, "LANOPS - Paso 2"')
a("End Sub"); a("")
a("Private Function Intento(db As DAO.Database, ByVal sql As String) As String")
a("    On Error Resume Next"); a("    db.Execute sql, dbFailOnError")
a('    If Err.Number = 0 Then Intento = "ADMITIDO (mal)" Else Intento = "rechazado (bien) - error " & Err.Number & ": " & Err.Description')
a("    Err.Clear"); a("End Function"); a("")
a("Public Sub Paso3_Probar()")
a("    Dim ws As DAO.Workspace, db As DAO.Database, r As String")
a("    Set ws = DBEngine.Workspaces(0): Set db = CurrentDb")
a("    ws.BeginTrans")
a('    r = "1) Evaluacion de un usuario que no existe (9999): " & Intento(db, "INSERT INTO EVALUACIONES (usuario, vacante, evaluador, fecha, d1_match_cv, d2_north_star, d3_compensacion, d4_cultura, d5_red_flags, [global], banda, hash_cv) VALUES (9999, 1, 1, Date(), 3, 3, 3, 3, 3, 3, ""Media"", ""prueba"")") & vbCrLf & vbCrLf')
a('    r = r & "2) Entidad de tipo no admitido: " & Intento(db, "INSERT INTO ENTIDADES (nombre, tipo) VALUES (""Prueba LANOPS"", ""empresa"")") & vbCrLf & vbCrLf')
a('    r = r & "3) Vacante duplicada (mismo hash): " & Intento(db, "INSERT INTO VACANTES (empresa, puesto, estado, fuente, hash) SELECT TOP 1 empresa, puesto, ""abierta"", ""manual"", hash FROM VACANTES") & vbCrLf & vbCrLf')
a('    r = r & "4) Mismo evaluador puntua dos veces el mismo par con el mismo CV: " & Intento(db, "INSERT INTO EVALUACIONES (usuario, vacante, evaluador, fecha, d1_match_cv, d2_north_star, d3_compensacion, d4_cultura, d5_red_flags, [global], banda, hash_cv) SELECT TOP 1 usuario, vacante, evaluador, fecha, 3, 3, 3, 3, 3, 3, ""Media"", hash_cv FROM EVALUACIONES") & vbCrLf & vbCrLf')
a('    r = r & "Relaciones con integridad: " & Relaciones(db) & " (esperadas: 15)"')
a("    ws.Rollback")
a("    Debug.Print r"); a('    MsgBox r, vbInformation, "LANOPS - Paso 3 (no se ha guardado nada)"')
a("End Sub")
open("LANOPS_montaje.bas", "w", encoding="cp1252", newline="\r\n").write("\n".join(L) + "\n")
print(len(L), "lineas"); print(cnt)
